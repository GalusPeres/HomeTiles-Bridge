"""Timer sound select: what the panel plays when a voice timer finished.

The built-in chimes are generated by the panel itself; the user's own files
in <config>/hometiles/sounds are played by the Bridge when the panel asks
(voice_timers.py). Home Assistant keeps the choice (restore state) and the
satellite sends it to the panel on every connect.
"""

from __future__ import annotations

from datetime import timedelta
import logging

from homeassistant.components.select import SelectEntity
from homeassistant.config_entries import ConfigEntry
from homeassistant.core import HomeAssistant
from homeassistant.helpers.entity import EntityCategory
from homeassistant.helpers.event import async_track_time_interval
from homeassistant.helpers.restore_state import RestoreEntity

from .assist import ASSIST_SATELLITES_KEY
from .const import DOMAIN
from .device_helpers import entry_device_id, entry_device_info
from . import voice_timers

_LOGGER = logging.getLogger(__name__)

# New sound files show up within a minute.
SOUND_FILES_INTERVAL = timedelta(seconds=60)


class HomeTilesTimerSoundSelect(SelectEntity, RestoreEntity):
    """Sound for finished voice timers: built-in chimes, own files or off."""

    _attr_has_entity_name = True
    _attr_translation_key = "timer_sound"
    _attr_entity_category = EntityCategory.CONFIG
    _attr_icon = "mdi:bell-ring"
    _attr_should_poll = False

    def __init__(self, hass: HomeAssistant, entry: ConfigEntry) -> None:
        self._entry_id = entry.entry_id
        self._attr_device_info = entry_device_info(entry)
        self._attr_unique_id = voice_timers.timer_sound_select_unique_id(entry_device_id(entry))
        self._files: list[str] = []
        self._option = voice_timers.DEFAULT_SOUND
        self._unsubscribe = None

    @property
    def options(self) -> list[str]:
        options = [*voice_timers.BUILTIN_SOUNDS, *self._files]
        # A chosen file stays listed while it is missing for a moment.
        if self._option not in options and self._option != voice_timers.SOUND_OFF:
            options.append(self._option)
        return [*options, voice_timers.SOUND_OFF]

    @property
    def current_option(self) -> str | None:
        return self._option

    def _effective(self) -> str:
        # A chosen file that is gone rings with the default chime, not silence.
        if (self._option in voice_timers.BUILTIN_SOUNDS or self._option == voice_timers.SOUND_OFF
                or self._option in self._files):
            return self._option
        return voice_timers.DEFAULT_SOUND

    def _store(self) -> bool:
        """Store the sound the panel should use; True when it changed."""
        sounds = self.hass.data.setdefault(DOMAIN, {}).setdefault(voice_timers.TIMER_SOUNDS_KEY, {})
        effective = self._effective()
        changed = sounds.get(self._entry_id) != effective
        sounds[self._entry_id] = effective
        return changed

    async def _async_send(self) -> None:
        satellite = (self.hass.data.get(DOMAIN, {})
                     .get(ASSIST_SATELLITES_KEY, {}).get(self._entry_id))
        if satellite is not None:
            # A panel that is offline gets it on its next connect.
            await satellite.async_send_timer_sound()

    async def async_select_option(self, option: str) -> None:
        if option not in self.options:
            raise ValueError(f"Unknown timer sound: {option}")
        self._option = option
        self._store()
        self.async_write_ha_state()
        await self._async_send()

    async def _async_refresh_files(self, _now=None, send: bool = True) -> None:
        directory = self.hass.config.path(*voice_timers.SOUNDS_DIR)
        files = await self.hass.async_add_executor_job(voice_timers.list_sound_files, directory)
        if files != self._files:
            self._files = files
            self.async_write_ha_state()
            if self._store() and send:
                await self._async_send()

    async def async_added_to_hass(self) -> None:
        await super().async_added_to_hass()
        last = await self.async_get_last_state()
        if last is not None and (last.state in voice_timers.BUILTIN_SOUNDS
                                 or last.state == voice_timers.SOUND_OFF
                                 or voice_timers.valid_sound_file_name(last.state)):
            self._option = last.state
        # The files first, so a restored own file is not taken for a missing one.
        await self._async_refresh_files(send=False)
        self._store()
        self._unsubscribe = async_track_time_interval(
            self.hass, self._async_refresh_files, SOUND_FILES_INTERVAL)
        await self._async_send()

    async def async_will_remove_from_hass(self) -> None:
        if self._unsubscribe is not None:
            self._unsubscribe()
            self._unsubscribe = None
        self.hass.data.get(DOMAIN, {}).get(voice_timers.TIMER_SOUNDS_KEY, {}).pop(self._entry_id, None)
        await super().async_will_remove_from_hass()
